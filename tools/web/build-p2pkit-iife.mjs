#!/usr/bin/env node
/**
 * Bundles the in-tree hardened p2pkit sources (platform/web/p2pkit/src, see
 * platform/web/p2pkit/UPSTREAM.md) into a classic-script IIFE at
 * platform/web/dist/p2pkit.iife.js exposing globalThis.P2PKIT_IIFE.
 *
 * webrtc_glue.js resolves that global lazily at runtime, and
 * tools/web/build-emscripten.sh prepends the bundle to dunecity.js so the
 * browser runtime always sees it. The bundle is committed; regenerate with:
 *
 *   npm ci --prefix tools/webrtc-signaling   # installs the esbuild devDependency
 *   node tools/web/build-p2pkit-iife.mjs
 *
 * The export surface is exactly what the browser glue consumes. The trimmed
 * in-tree copy has no negotiate/sdp modules, so upstream p2pkit helpers such
 * as isInitiator/chooseTransport/extractIP are intentionally absent; the glue
 * derives offer/answer roles from room host/client semantics instead.
 */
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { webcrypto } from 'node:crypto';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC_DIR = path.join(ROOT, 'platform', 'web', 'p2pkit', 'src');
const OUT_FILE = path.join(ROOT, 'platform', 'web', 'dist', 'p2pkit.iife.js');
const SIGNALING_DIR = path.join(ROOT, 'tools', 'webrtc-signaling');

const ENTRY = `
import { RTCTransport } from './transports/rtc.js'
import { DEFAULT_ICE_SERVERS } from './utils/ice.js'
import { Emitter } from './utils/emitter.js'
import { randomId } from './utils/id.js'

export { RTCTransport, DEFAULT_ICE_SERVERS, Emitter, randomId }
`;

const EXPECTED_KEYS = ['DEFAULT_ICE_SERVERS', 'Emitter', 'RTCTransport', 'randomId'];

// esbuild is a devDependency of the signaling package (see README); resolve it
// from there so this script works without a top-level node_modules.
const requireFromSignaling = createRequire(path.join(SIGNALING_DIR, 'package.json'));
let esbuild;
try {
  esbuild = requireFromSignaling('esbuild');
} catch {
  console.error('ERROR: esbuild is not installed.');
  console.error('       Run: npm ci --prefix tools/webrtc-signaling');
  process.exit(1);
}

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });

await esbuild.build({
  stdin: {
    contents: ENTRY,
    resolveDir: SRC_DIR,
    loader: 'ts',
  },
  bundle: true,
  format: 'iife',
  globalName: 'P2PKIT_IIFE',
  target: ['es2020'],
  outfile: OUT_FILE,
  charset: 'utf8',
  logLevel: 'silent',
  banner: {
    js: [
      '// Generated by tools/web/build-p2pkit-iife.mjs from platform/web/p2pkit/src — do not edit.',
      '// Provenance and hardening notes: platform/web/p2pkit/UPSTREAM.md.',
      '// Exposes globalThis.P2PKIT_IIFE for webrtc_glue.js (Emscripten browser runtime).',
    ].join('\n'),
  },
  footer: { js: 'globalThis.P2PKIT_IIFE = P2PKIT_IIFE;' },
});

// Self-check: the bundle must load in a bare context and expose exactly the
// expected surface, so a bad regenerate cannot silently break the glue.
const sandbox = {
  TextEncoder,
  TextDecoder,
  performance,
  queueMicrotask,
  setInterval,
  clearInterval,
  setTimeout,
  clearTimeout,
  crypto: webcrypto,
  Event,
  console,
};
vm.runInNewContext(fs.readFileSync(OUT_FILE, 'utf8'), sandbox, { filename: 'p2pkit.iife.js' });
const kit = sandbox.P2PKIT_IIFE;
if (!kit) throw new Error('bundle did not expose P2PKIT_IIFE');
const keys = Object.keys(kit).sort();
const expected = [...EXPECTED_KEYS].sort();
if (keys.join(',') !== expected.join(',')) {
  throw new Error(`bundle exports [${keys}] but expected [${expected}]`);
}
for (const name of EXPECTED_KEYS) {
  if (typeof kit[name] !== 'function' && !Array.isArray(kit[name])) {
    throw new Error(`bundle export ${name} is not usable`);
  }
}

console.log(`OK: ${path.relative(ROOT, OUT_FILE)} exports ${keys.join(', ')}`);
